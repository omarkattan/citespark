const {readFileSync}=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const src=readFileSync(__dirname+'/../src/lib/prompts.js','utf8').replace(/^import .*;\n/gm,'').replace(/export /g,'');
const ctx=vm.createContext({queryKey:s=>s.toLowerCase().trim(),containsSearchBrand:(s,names)=>names.filter(Boolean).some(n=>s.toLowerCase().includes(n.toLowerCase()))});
vm.runInContext(src,ctx);
const generic={text:'What should I consider before choosing an agency?',intent:'problem'};
const rec={text:'Who are the best SEO agencies in Dubai?',intent:'discovery',ai_search_volume:null};
const config={category:'SEO services',market:'Dubai',brand:'Example Brand',domain:'example.com',count:2};
assert.equal(ctx.discoveryFirst([generic,rec],config)[0].text,rec.text);
assert.equal(ctx.discoveryFirst([generic],config)[0].text,'Who would you recommend for SEO services in Dubai?');
assert.equal(ctx.discoveryFirst([rec,rec,generic],config).length,2);
assert.equal(ctx.discoveryFirst([generic],{...config,count:1}).length,1);
assert.match(ctx.discoveryFirst([generic],{...config,category:'خدمات التسويق',market:'دبي',language:'ar'})[0].text,/بمن تنصح/);
assert.equal(ctx.discoveryFirst([generic],{...config,category:'Example Brand'})[0].text,generic.text);
assert.equal(ctx.discoveryFirst([generic],config)[0].ai_search_volume,null);
assert.match(ctx.discoveryFirst([generic],{...config,category:'skincare products'})[0].text,/skincare products/);
assert.doesNotMatch(ctx.discoveryFirst([generic],{...config,category:'skincare products'})[0].text,/agencies/);
console.log('PASS: discovery priority, fallback, deduplication, limit, Arabic, brand exclusion, provenance, niche');
